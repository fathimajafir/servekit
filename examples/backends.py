"""Example backends.

They are deliberately fake so the framework can be exercised without a GPU. Swapping
one for a real model is a single class with the same five methods - see
``docs/adding-a-service.md``.
"""

from __future__ import annotations

import asyncio
import time
from typing import AsyncIterator, Optional

from servekit import (
    Capability,
    Health,
    LatencyClass,
    ModelSpec,
    Request,
    Response,
    StreamEvent,
    Usage,
)


def prompt_of(request: Request) -> str:
    messages = request.payload.get("messages")
    if messages:
        last = messages[-1]
        return str(last.get("content", "")) if isinstance(last, dict) else str(last)
    return str(request.payload.get("input") or request.payload.get("prompt") or "")


class SimulatedLLM:
    """A chat model that streams word by word and reports its own load."""

    def __init__(
        self,
        spec: ModelSpec,
        latency_s: float = 0.25,
        tokens_per_s: float = 80.0,
        fail_after: Optional[int] = None,
    ) -> None:
        self.spec = spec
        self.latency_s = latency_s
        self.tokens_per_s = tokens_per_s
        self.fail_after = fail_after
        self._inflight = 0
        self._calls = 0
        self.warm = False

    # -- Backend protocol --------------------------------------------------

    async def health(self) -> Health:
        return Health(ok=True, inflight=self._inflight, queue_depth=0)

    async def warmup(self) -> None:
        await asyncio.sleep(0.01)
        self.warm = True

    async def invoke(self, request: Request) -> Response:
        self._calls += 1
        if self.fail_after is not None and self._calls > self.fail_after:
            raise RuntimeError("simulated upstream failure")
        self._inflight += 1
        try:
            await asyncio.sleep(self.latency_s)
            text = self._answer(request)
            return Response(
                request_id=request.request_id,
                model=self.spec.id,
                output={"text": text},
                usage=Usage(
                    input_units=len(prompt_of(request).split()),
                    output_units=len(text.split()),
                    unit=self.spec.unit,
                ),
            )
        finally:
            self._inflight -= 1

    async def stream(self, request: Request) -> AsyncIterator[StreamEvent]:
        self._inflight += 1
        try:
            await asyncio.sleep(min(self.latency_s, 0.1))
            words = self._answer(request).split()
            produced = 0
            for word in words:
                await asyncio.sleep(1.0 / self.tokens_per_s)
                produced += 1
                yield StreamEvent(
                    request_id=request.request_id,
                    delta={"text": word + " "},
                )
            yield StreamEvent(
                request_id=request.request_id,
                done=True,
                usage=Usage(
                    input_units=len(prompt_of(request).split()),
                    output_units=produced,
                    unit=self.spec.unit,
                ),
            )
        finally:
            self._inflight -= 1

    async def drain(self) -> None:
        while self._inflight > 0:
            await asyncio.sleep(0.01)

    # -- helpers -----------------------------------------------------------

    def _answer(self, request: Request) -> str:
        prompt = prompt_of(request).strip() or "nothing"
        return (
            f"[{self.spec.id}] You asked about {prompt!r}. "
            f"This reply is generated by the {self.spec.id} model, "
            f"which costs tier {self.spec.cost_tier} and runs at concurrency "
            f"{self.spec.max_concurrency}."
        )


class SimulatedTTS:
    """Same contract, completely different modality - that is the framework."""

    def __init__(self, spec: ModelSpec, latency_s: float = 0.3) -> None:
        self.spec = spec
        self.latency_s = latency_s
        self._inflight = 0

    async def health(self) -> Health:
        return Health(ok=True, inflight=self._inflight)

    async def warmup(self) -> None:
        return None

    async def invoke(self, request: Request) -> Response:
        self._inflight += 1
        try:
            text = prompt_of(request) or "hello"
            await asyncio.sleep(self.latency_s)
            # bytes of silence would be more honest, but a marker is easier to eyeball
            audio = f"AUDIO[{self.spec.id}]:{text}".encode("utf-8")
            return Response(
                request_id=request.request_id,
                model=self.spec.id,
                output=audio,
                usage=Usage(output_units=len(text), unit="second"),
                metadata={"content_type": "audio/wav"},
            )
        finally:
            self._inflight -= 1

    async def stream(self, request: Request) -> AsyncIterator[StreamEvent]:
        response = await self.invoke(request)
        yield StreamEvent(request_id=request.request_id, delta=response.output)
        yield StreamEvent(request_id=request.request_id, done=True, usage=response.usage)

    async def drain(self) -> None:
        while self._inflight > 0:
            await asyncio.sleep(0.01)


def small_llm() -> SimulatedLLM:
    return SimulatedLLM(
        ModelSpec(
            id="chat-small",
            capability=Capability.TEXT_GENERATE,
            cost_tier=1,
            latency_class=LatencyClass.REALTIME,
            max_concurrency=16,
            unit="token",
        ),
        latency_s=0.08,
        tokens_per_s=200,
    )


def large_llm() -> SimulatedLLM:
    return SimulatedLLM(
        ModelSpec(
            id="chat-large",
            capability=Capability.TEXT_GENERATE,
            cost_tier=8,
            latency_class=LatencyClass.INTERACTIVE,
            max_concurrency=4,
            unit="token",
        ),
        latency_s=0.6,
        tokens_per_s=40,
    )


def tts_engine() -> SimulatedTTS:
    return SimulatedTTS(
        ModelSpec(
            id="tts-v1",
            capability=Capability.AUDIO_SPEECH,
            cost_tier=3,
            latency_class=LatencyClass.REALTIME,
            max_concurrency=8,
            unit="second",
        )
    )
